#!/usr/bin/env python3
"""Generate offline Dart catalogues and Android notifications; --check never writes."""
import argparse
import json
import re
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
L10N = ROOT / "lib/l10n"
LANGUAGES = ("fr", "nl", "de", "es", "it", "pl", "pt", "ro", "sv", "da", "fi", "cs")
BRAND = {
    "appTitle": "Rabochiy VPN", "tabHome": "VPN", "homeGetProAccent": "PRO",
    "homeGetProSuffix": "", "accountPlanPremium": "PRO", "premiumHeroAccent": "Pro",
}
EXTRA = {"serversCountOne", "serversCountOther", "errorGeneric", "reconnecting"}
OPTIONAL = {"serversCountFew", "serversCountMany"}


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate key: {key}")
        result[key] = value
    return result


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=unique_object)


def dart_string(text):
    return json.dumps(text, ensure_ascii=False).replace("$", r"\$")


def outputs():
    getters = re.findall(r"String get (\w+);", (L10N / "app_localizations.dart").read_text())
    aliases = read_json(L10N / "catalogs/aliases.json")
    required = set(getters) - set(aliases) - set(BRAND) - {"privacyPolicyContent"}
    lines = [
        "// Generated by tools/generate_localizations.py. Edit catalogues and policies instead.",
        "import 'package:intl/intl.dart' as intl;",
        "import 'app_localizations.dart';", "",
        "class AppLocalizationsEu extends AppLocalizations {",
        "  AppLocalizationsEu(String languageCode)",
        "      : _messages = _catalogues[languageCode]!,",
        "        super(languageCode == 'pt' ? 'pt_PT' : languageCode);", "",
        "  final Map<String, String> _messages;",
        "  static const languageCodes = <String>[" + ", ".join(dart_string(c) for c in LANGUAGES) + "];", "",
    ]
    for key in getters:
        lines += ["  @override", f"  String get {key} => _messages['{key}']!;"]
    lines += [
        "  @override", "  String errorGeneric(String details) =>",
        "      _messages['errorGeneric']!.replaceAll('{details}', details);", "",
        "  @override", "  String serversCount(num count) {",
        "    final pattern = intl.Intl.plural(count,",
        "      one: _messages['serversCountOne'],",
        "      few: _messages['serversCountFew'],",
        "      many: _messages['serversCountMany'],",
        "      other: _messages['serversCountOther']!, locale: localeName);",
        "    return pattern.replaceAll('{count}', intl.NumberFormat.decimalPattern(localeName).format(count));",
        "  }", "}", "", "const _catalogues = <String, Map<String, String>>{",
    ]
    generated = {}
    for code in LANGUAGES:
        data = read_json(L10N / f"catalogs/{code}.json")
        missing = (required | EXTRA) - data.keys()
        unknown = data.keys() - required - EXTRA - OPTIONAL
        if missing or unknown:
            raise ValueError(f"{code}: missing {sorted(missing)}; unknown {sorted(unknown)}")
        if not all(isinstance(v, str) and v.strip() for v in data.values()):
            raise ValueError(f"{code}: empty or non-string translation")
        for key, value in data.items():
            expected = {"count"} if key.startswith("serversCount") else {"details"} if key == "errorGeneric" else set()
            if set(re.findall(r"\{(\w+)\}", value)) != expected:
                raise ValueError(f"{code}.{key}: wrong placeholders")
        data.update(BRAND)
        for key, source in aliases.items():
            data[key] = data[source]
        data["privacyPolicyContent"] = (L10N / f"policies/{code}.txt").read_text(encoding="utf-8").strip()
        assert set(getters) <= data.keys()
        lines.append(f"  {dart_string(code)}: {{")
        for key, value in sorted(data.items()):
            lines.append(f"    {dart_string(key)}: {dart_string(value)},")
        lines.append("  },")
        # These resources are consumed by the GW foreground service.
        resources = {
            "vlee_notif_title": BRAND["appTitle"],
            "vlee_notif_channel": BRAND["appTitle"],
            "vlee_notif_connected": data["securelyConnected"],
            "vlee_notif_reconnecting": data["reconnecting"],
        }
        xml = ['<?xml version="1.0" encoding="utf-8"?>', '<resources>']
        for key, value in resources.items():
            value = escape(value).replace("'", r"\'")
            xml.append(f'    <string name="{key}">{value}</string>')
        xml.append('</resources>')
        path = ROOT / f"android/vlee_engine/src/main/res/values-{code}/strings.xml"
        generated[path] = "\n".join(xml) + "\n"
    lines.append("};")
    generated[L10N / "app_localizations_eu.dart"] = "\n".join(lines) + "\n"
    return generated


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        raise SystemExit("Stale generated files: " + ", ".join(stale))
    print(f"Validated {len(LANGUAGES)} complete catalogues, policies and Android notifications.")


if __name__ == "__main__":
    main()
